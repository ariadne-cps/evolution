namespace Ariadne {

/** @brief One sampled path, including the point at every integer index.
 *  @details events[i] records the selected event from index i to i+1;
 *  nullopt denotes ordinary progression. The path preserves its initial
 *  seed index even after several independent event branches. blocked means
 *  that no successor is enabled before the requested termination index.
 */
struct HybridDiscreteTimeApproximatePath {
    SizeType initial_index = 0u;
    std::vector<HybridApproximatePoint> points;
    std::vector<std::optional<DiscreteEvent>> events;
    Bool blocked = false;
};

/** @brief A collection of all point paths generated by discrete hybrid branching.
 *  @details A single sampled initial state may produce multiple paths.
 *  Unlike a fixed-size orbit vector, the number of paths can grow at
 *  every index. Each path retains its entire pre-branch history.
 */
class HybridDiscreteTimeApproximateOrbit {
  public:
    using PathType = HybridDiscreteTimeApproximatePath;
    SizeType number_of_trajectories() const { return _paths.size(); }
    const std::vector<PathType>& trajectories() const { return _paths; }
    const PathType& trajectory(SizeType i) const { return _paths.at(i); }

  private:
    std::vector<PathType> _paths;
    friend class HybridDiscreteTimeEvolver<ApproximateTag>;
};

/** @brief Initial sampling and explicit branching-resource policy. */
template<>
class HybridDiscreteTimeEvolverConfiguration<ApproximateTag> : public ConfigurationInterface {
  public:
    HybridDiscreteTimeEvolverConfiguration() = default;
    Void set_sampling_counts(SamplingCounts counts) {
        for (const auto& item: counts)
            ARIADNE_PRECONDITION(item.second > 0u);
        _sampling_counts = std::move(counts);
    }
    Void set_sampling_count(RealVariable variable, Nat count) {
        ARIADNE_PRECONDITION(count > 0u);
        ARIADNE_PRECONDITION(!_sampling_counts.has_key(variable));
        _sampling_counts.insert(variable, count);
    }
    Void clear_sampling_counts() { _sampling_counts.remove_keys(_sampling_counts.keys()); }
    const SamplingCounts& sampling_counts() const { return _sampling_counts; }

    //! Abort explicitly when branching would exceed this limit; never truncate.
    SizeType maximum_paths() const { return _maximum_paths; }
    Void set_maximum_paths(SizeType limit) {
        ARIADNE_PRECONDITION(limit > 0u);
        _maximum_paths = limit;
    }
    OutputStream& _write(OutputStream& os) const override;

  private:
    SamplingCounts _sampling_counts;
    SizeType _maximum_paths = 10000u;
};

/** @brief Branching sampled hybrid evolution with exact integer step indices.
 *  @details Both an enabled transition and an admissible progression consume
 *  one tick. Every enabled alternative is retained as a separate trajectory,
 *  including competing transitions and overlapping permissive progression.
 *  Source guards refer to the pre-state. Unknown numerical boundary cases
 *  are reported as errors, not resolved by priority. Inclusion modes need
 *  an explicit per-tick input policy, and all initial point samples come
 *  from paving-independent bisection. No set semantics are implied.
 *
 *  The generic Approximate EvolverInterface returns Orbit<InitialType>,
 *  whose fixed initial cardinality cannot represent dynamically forked
 *  paths, so this specialization deliberately exposes the branching
 *  result directly instead of silently flattening or dropping paths.
 */
template<>
class HybridDiscreteTimeEvolver<ApproximateTag> {
  public:
    using Paradigm = ApproximateTag;
    using SystemType = DiscreteTimeHybridAutomatonInterface;
    using InitialType = HybridApproximatePoint;
    using InitialListType = Vector<InitialType>;
    using TerminationType = Integer;
    using TimeType = Integer;
    using OrbitType = HybridDiscreteTimeApproximateOrbit;
    using ResultType = OrbitType;
    using ConfigurationType = HybridDiscreteTimeEvolverConfiguration<ApproximateTag>;

    explicit HybridDiscreteTimeEvolver(const SystemType& system);
    HybridDiscreteTimeEvolver(const SystemType& system, const InputSamplingPolicy& policy);
    HybridDiscreteTimeEvolver(const HybridDiscreteTimeEvolver&);

    HybridDiscreteTimeEvolver* clone() const { return new HybridDiscreteTimeEvolver(*this); }
    const SystemType& system() const { return *_system; }
    ConfigurationType& configuration() { return *_configuration; }
    const ConfigurationType& configuration() const { return *_configuration; }

    OrbitType orbit(const InitialType&, const TerminationType&) const;
    OrbitType orbit(const InitialListType&, const TerminationType&) const;
    OrbitType orbit(const UpperBoxType&, DiscreteLocation, const TerminationType&) const;

  private:
    std::shared_ptr<const SystemType> _system;
    std::shared_ptr<ConfigurationType> _configuration;
    std::shared_ptr<const InputSamplingPolicy> _input_sampling;
};

} // namespace Ariadne

